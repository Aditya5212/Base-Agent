"""Parallel multi-query hybrid search and cross-query fusion service.

Enables agents to explore the knowledge base across multiple query angles simultaneously:
- Accepts a list of diverse queries directly from the calling agent
- Executes parallel hybrid searches (dense + sparse + RRF) across all queries
- Fuses and re-ranks retrieved chunks using cross-query Reciprocal Rank Fusion (RRF)
  with multi-query coverage tracking.
"""

from __future__ import annotations

import asyncio
import logging

from langchain_core.documents import Document

from app.core.rag_config import get_rag_config
from app.services.retriever import _compute_chunk_fingerprint, hybrid_search

logger = logging.getLogger(__name__)


def cross_query_reciprocal_rank_fusion(
    query_results: list[tuple[str, list[Document]]],
    top_k: int = 8,
    k_constant: float = 60.0,
    multi_hit_bonus: float = 0.05,
    active_thread_id: str | None = None,
    thread_boost: float = 0.05,
) -> list[Document]:
    """Fuses documents retrieved across multiple queries using reciprocal rank fusion with multi-query bonuses.

    Formula:
        Score(d) = Sum_{q in Q} [ 1.0 / (k + rank(d, q)) ] + (num_matched_queries - 1) * multi_hit_bonus
    Additionally awards thread_boost to documents matching active_thread_id.
    """
    doc_registry: dict[str, Document] = {}
    fused_scores: dict[str, float] = {}
    matched_queries: dict[str, list[str]] = {}
    per_query_ranks: dict[str, dict[str, int]] = {}

    for query, docs in query_results:
        per_query_ranks[query] = {}
        for rank, doc in enumerate(docs, 1):
            fp = _compute_chunk_fingerprint(doc)
            if fp not in doc_registry:
                doc_registry[fp] = doc
                matched_queries[fp] = []

            if query not in matched_queries[fp]:
                matched_queries[fp].append(query)
            per_query_ranks[query][fp] = rank

            # Base RRF score for this rank position
            rrf_term = 1.0 / (k_constant + rank)
            fused_scores[fp] = fused_scores.get(fp, 0.0) + rrf_term

    # Apply multi-hit bonus for chunks matching multiple angles of the research queries
    for fp, queries_matched in matched_queries.items():
        if len(queries_matched) > 1:
            bonus = (len(queries_matched) - 1) * multi_hit_bonus
            fused_scores[fp] += bonus

    # Apply active thread bonus to prioritize conversation-specific knowledge
    for fp, doc in doc_registry.items():
        doc_thread = doc.metadata.get("thread_id")
        if active_thread_id and doc_thread == active_thread_id:
            fused_scores[fp] += thread_boost
            doc.metadata["is_thread_document"] = True
            doc.metadata["retrieval_scope"] = "thread"
        else:
            doc.metadata["is_thread_document"] = False
            doc.metadata["retrieval_scope"] = "global" if not doc_thread else "other_thread"

    # Sort descending by final fused score
    sorted_fps = sorted(fused_scores.keys(), key=lambda fp: fused_scores[fp], reverse=True)

    final_docs: list[Document] = []
    for fp in sorted_fps[:top_k]:
        doc = doc_registry[fp]
        # Attach exploration telemetry to metadata
        doc.metadata["cross_rrf_score"] = round(fused_scores[fp], 6)
        doc.metadata["matched_queries"] = matched_queries[fp]
        doc.metadata["matched_query_count"] = len(matched_queries[fp])
        final_docs.append(doc)

    return final_docs


async def multi_query_hybrid_search(
    queries: list[str],
    user_id: str,
    preset: str = "balanced",
    top_k_final: int = 8,
    thread_id: str | None = None,
    scope: Any = None,
) -> list[Document]:
    """Executes parallel hybrid search for an agent-provided list of queries and fuses the results.

    Args:
        queries: List of search queries/perspectives generated by the calling agent.
        user_id: Caller's user_id for strict tenant isolation.
        preset: RAG retrieval preset ('high_precision', 'balanced', 'high_recall').
        top_k_final: Maximum number of fused documents to return.
        thread_id: Optional conversation thread ID for thread-aware retrieval scoping.
        scope: Optional explicit RetrievalScope.

    Returns:
        Ranked and deduplicated list of fused Document objects.
    """
    cleaned_queries = [q.strip() for q in queries if q and q.strip()]
    if not cleaned_queries:
        return []

    rag_cfg = get_rag_config(preset)

    # Launch parallel hybrid searches for each query provided by the agent
    tasks = [
        hybrid_search(
            query=q,
            config=rag_cfg,
            filter_dict={"user_id": user_id},
            thread_id=thread_id,
            scope=scope,
        )
        for q in cleaned_queries
    ]

    results = await asyncio.gather(*tasks, return_exceptions=True)

    query_results: list[tuple[str, list[Document]]] = []
    for q, res in zip(cleaned_queries, results):
        if isinstance(res, BaseException):
            if not isinstance(res, Exception):
                raise res
            logger.warning("Query '%s' failed during hybrid retrieval: %s", q, res)
            continue
        query_results.append((q, res))

    if not query_results:
        raise RuntimeError("All multi-query retrieval requests failed")

    return cross_query_reciprocal_rank_fusion(
        query_results=query_results,
        top_k=top_k_final,
        active_thread_id=thread_id,
    )
